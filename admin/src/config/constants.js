export const formatFeatureLabel = (code = "") => {
  if (!code) return "";
  return FEATURE_LABELS[code] || String(code).replace(/^ftr_/, "").replace(/_/g, " ").replace(/\b\w/g, (letter) => letter.toUpperCase());
};
