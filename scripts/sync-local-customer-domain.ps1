param(
    [Parameter(Mandatory = $true)]
    [string]$Domain,

    [string]$HostsPath = "C:\Windows\System32\drivers\etc\hosts",
    [string]$SitesEnabledPath = "C:\laragon\etc\apache2\sites-enabled",
    [string]$LaragonApacheRoot = "C:\laragon\bin\apache",
    [string]$ConfigFileName = "zz-arcade-storefront-dynamic.conf",
    [int]$StorefrontPort = 3000
)

function Normalize-Domain {
    param([string]$Value)

    $normalized = ""

    if ($null -ne $Value) {
        $normalized = [string]$Value
    }

    $normalized = $normalized.Trim().ToLowerInvariant()
    $normalized = $normalized -replace '^https?://', ''
    $normalized = $normalized -replace '/.*$', ''
    $normalized = $normalized -replace ':\d+$', ''

    return $normalized
}

$normalizedDomain = Normalize-Domain -Value $Domain

if ([string]::IsNullOrWhiteSpace($normalizedDomain)) {
    throw "A valid domain is required."
}

$configPath = Join-Path $SitesEnabledPath $ConfigFileName
$configContent = @"
# Auto-generated by Arcade local storefront domain sync.
<VirtualHost *:80>
    ServerName storefront.dynamic.arcade.local
    ServerAlias *

    ProxyPreserveHost On
    ProxyPass / http://127.0.0.1:$StorefrontPort/
    ProxyPassReverse / http://127.0.0.1:$StorefrontPort/
</VirtualHost>
"@

$apacheConfigChanged = $false

if (-not (Test-Path $SitesEnabledPath)) {
    throw "Laragon Apache sites-enabled path was not found: $SitesEnabledPath"
}

$existingConfig = ""
if (Test-Path $configPath) {
    $existingConfig = Get-Content -Raw -Path $configPath -ErrorAction Stop
}

if ($existingConfig -ne $configContent) {
    try {
        Set-Content -Path $configPath -Value $configContent -Encoding UTF8 -ErrorAction Stop
    } catch {
        throw "Unable to write Laragon Apache config. Run your terminal as Administrator and try again."
    }

    $apacheConfigChanged = $true
}

if (-not (Test-Path $HostsPath)) {
    throw "Windows hosts file was not found: $HostsPath"
}

$markerStart = "# >>> Arcade dynamic storefront domains >>>"
$markerEnd = "# <<< Arcade dynamic storefront domains <<<"
$existingHosts = Get-Content -Path $HostsPath -ErrorAction Stop

$outsideSection = @()
$currentManagedLines = @()
$insideManagedSection = $false

foreach ($line in $existingHosts) {
    if ($line -eq $markerStart) {
        $insideManagedSection = $true
        continue
    }

    if ($line -eq $markerEnd) {
        $insideManagedSection = $false
        continue
    }

    if ($insideManagedSection) {
        $currentManagedLines += $line
        continue
    }

    if (-not $insideManagedSection) {
        $outsideSection += $line
    }
}

$managedDomains = @()
foreach ($line in $currentManagedLines) {
    if ($line -match '^\s*127\.0\.0\.1\s+([^\s#]+)') {
        $candidate = Normalize-Domain -Value $Matches[1]
        if ($candidate) {
            $managedDomains += $candidate
        }
    }
}

$managedDomains += $normalizedDomain
$managedDomains = $managedDomains | Sort-Object -Unique

$managedSection = @($markerStart)
foreach ($mappedDomain in $managedDomains) {
    $managedSection += "127.0.0.1 $mappedDomain"
}
$managedSection += $markerEnd

$finalHostsContent = @()
$finalHostsContent += $outsideSection
$finalHostsContent += ""
$finalHostsContent += $managedSection

try {
    Set-Content -Path $HostsPath -Value $finalHostsContent -Encoding ASCII -ErrorAction Stop
} catch {
    throw "Windows hosts file update failed. Run Laragon / Next terminal as Administrator, then try Save Domain again."
}

[pscustomobject]@{
    status = $true
    domain = $normalizedDomain
    apacheConfigPath = $configPath
    apacheConfigChanged = $apacheConfigChanged
    apacheReloadRequired = $apacheConfigChanged
} | ConvertTo-Json -Compress
